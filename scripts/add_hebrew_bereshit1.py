"""One-shot helper: augment tafsir-bereshit-1-alignment.json with Hebrew anchors.

For every JA↔EN pair in the existing Bereshit 1 alignment file we add an
optional `he` substring of the verse's biblical Hebrew, where one exists.
The script enforces the same substring+cursor invariants the runtime
resolver uses (lib/alignment.ts:resolveVerseAlignment), so a typo would
fail validation rather than silently produce a broken alignment.

This was needed once because the prior alignment was generated as {ja, en}
pairs only. New chapters should be generated by the (now Hebrew-aware)
align_tafsir_english.py instead of by this script.

Run:
    python3 scripts/add_hebrew_bereshit1.py
"""

